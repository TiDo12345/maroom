<#
  Builds Maroom, creates the setup and uses it to install or update Maroom.
  © 2026 Timo Dörsam

  Steps:
   1. Make sure the sources are saved as UTF-8 with BOM (otherwise umlauts break)
   2. Compile Maroom.exe into dist\; on errors the installed version stays unchanged
   3. Build Maroom-Setup.exe into dist\ (Maroom.exe as resource, version taken from Maroom.exe)
   4. Run Maroom-Setup.exe /quiet: stops the running version cleanly (without swapping back),
      keeps the old EXE as Maroom.bak.exe, installs, registers and starts the new one; if the
      new one does not start, the old one is restored

  Afterwards dist\Maroom-Setup.exe is the finished setup to hand out (not in Git, see .gitignore).
  Uninstall: Settings > Apps > Installed apps > Maroom, or
             %LOCALAPPDATA%\Maroom\Maroom-Setup.exe /uninstall

  Usage (from the repository folder):  powershell -ExecutionPolicy Bypass -File .\build.ps1
  Build only, without installing (used by CI):  ... -File .\build.ps1 -NoInstall
#>
param([switch]$NoInstall)
$ErrorActionPreference = 'Stop'

$dist      = Join-Path $PSScriptRoot 'dist'
$csc       = 'C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe'
$app       = Join-Path $dist 'Maroom.exe'
$setup     = Join-Path $dist 'Maroom-Setup.exe'
$versionCs = Join-Path $dist 'SetupVersion.cs'
$icon      = Join-Path $PSScriptRoot 'icon\maroom.ico'   # generated by icon\IconGenerator.cs

function Write-Step($text) { Write-Host "-> $text" -ForegroundColor Cyan }
function Assert-Compiled($output) {
    if ($LASTEXITCODE -ne 0) {
        $output | Write-Host -ForegroundColor Red
        Write-Host 'Aborted: compilation failed, the installed version stays unchanged.' -ForegroundColor Red
        exit 1
    }
}

New-Item -ItemType Directory -Force $dist | Out-Null

Write-Step 'Saving sources as UTF-8 with BOM'
foreach ($file in 'Maroom.cs', 'Setup.cs', 'Container.cs') {
    $path = Join-Path $PSScriptRoot $file
    [IO.File]::WriteAllText($path, [IO.File]::ReadAllText($path), [Text.UTF8Encoding]::new($true))
}

Write-Step 'Compiling Maroom.exe'
Assert-Compiled (& $csc /nologo /target:winexe /platform:x64 /optimize+ "/win32icon:$icon" "/out:$app" (Join-Path $PSScriptRoot 'Maroom.cs') (Join-Path $PSScriptRoot 'Container.cs') 2>&1)
$version = (Get-Item $app).VersionInfo.FileVersion

Write-Step "Building Maroom-Setup.exe $version"
@"
[assembly: System.Reflection.AssemblyTitle("Maroom Setup")]
[assembly: System.Reflection.AssemblyProduct("Maroom")]
[assembly: System.Reflection.AssemblyCopyright("© 2026 Timo Dörsam")]
[assembly: System.Reflection.AssemblyVersion("$version")]
[assembly: System.Reflection.AssemblyFileVersion("$version")]
"@ | ForEach-Object { [IO.File]::WriteAllText($versionCs, $_, [Text.UTF8Encoding]::new($true)) }
Assert-Compiled (& $csc /nologo /target:winexe /platform:x64 /optimize+ "/win32icon:$icon" "/out:$setup" "/resource:$app,Maroom.exe" (Join-Path $PSScriptRoot 'Setup.cs') (Join-Path $PSScriptRoot 'Container.cs') $versionCs 2>&1)

if ($NoInstall) {
    Write-Host "Done: Maroom $version built (not installed). Setup: $setup" -ForegroundColor Green
    exit 0
}

Write-Step 'Installing with the setup'
# Not Start-Process -Wait: that would also wait for the Maroom process the setup starts
$process = Start-Process $setup -ArgumentList '/quiet' -PassThru
$process.WaitForExit()
$log = Join-Path $env:LOCALAPPDATA 'Maroom\setup.log'
if ($process.ExitCode -eq 3) {
    # This shell runs inside a Store app's container (see Container.cs): the setup continues via Explorer.
    Write-Host "Setup continues outside this sandboxed shell (started via Explorer). Result: setup.log in %LOCALAPPDATA%\Maroom (not visible from this shell)." -ForegroundColor Yellow
    exit 0
}
if ($process.ExitCode -ne 0) {
    Write-Host "Setup reported an error (exit code $($process.ExitCode)):" -ForegroundColor Red
    if (Test-Path $log) { Get-Content $log -Tail 5 | Write-Host }
    exit 1
}

Write-Host "Done: Maroom $version installed and started. Setup: $setup" -ForegroundColor Green
